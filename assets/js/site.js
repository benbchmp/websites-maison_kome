function parisWeekday() {
  const p = new Intl.DateTimeFormat('en-GB', { timeZone: 'Europe/Paris', weekday: 'short' }).formatToParts(new Date());
  return ['Mon','Tue','Wed','Thu','Fri','Sat','Sun'].indexOf(p.find(x => x.type === 'weekday').value);
}

function render() {
  const t = I18N[lang];
  document.documentElement.lang = HTML_LANG[lang];
  document.querySelectorAll('[data-t]').forEach(el => { el.textContent = t[el.dataset.t]; });
  ['rayonsTitle','rayonsSub','produitsTitle','produitsSub','avisTitle','infosTitle','hoursLabel','addressLabel','phoneLabel','phoneText','itinerary'].forEach(k => { $(k).textContent = t[k]; });
  $('sig').textContent = t.signature;
  $('sig2').textContent = t.signature;
  $('legal').textContent = t.legal;
  $('hoursShort').innerHTML = t.hoursShort.map(h => `<div><span>${h.d}</span><span>${h.h}</span></div>`).join('');

  $('track').innerHTML = RAYONS.map(([src, glyph], i) => `
    <figure>
      <div class="shelf"><img src="/assets/img/${src}" alt="${t.r[i][0]}" draggable="false" width="955" height="1142" ${i ? 'loading="lazy"' : ''}></div>
      <figcaption><div class="tag"><div class="tag-h"><span class="tag-n">${t.r[i][0]}</span><span class="tag-g">${glyph}</span></div><div class="tag-d">${t.r[i][1]}</div></div></figcaption>
    </figure>`).join('');

  $('cats').innerHTML = CATS.map(([glyph, ko, bg], i) => `
    <div class="cat" style="background:${bg}">
      <div class="cat-top"><span class="cat-g">${glyph}</span><span class="cat-k">${ko}</span></div>
      <div><div class="cat-n">${t.c[i][0]}</div><div class="cat-d">${t.c[i][1]}</div></div>
    </div>`).join('');

  $('reviews').innerHTML = REVIEWS.map(r => `
    <figure class="rev"><span class="stars">★★★★★</span><blockquote>« ${r.text} »</blockquote><figcaption>${r.name}</figcaption></figure>`).join('');

  const wd = parisWeekday();
  $('hours').innerHTML = HOURS.map((v, i) =>
    `<div class="hrow${v ? '' : ' closed'}${i === wd ? ' today' : ''}"><span>${t.days[i]}</span><span>${v ? `${v[0]}h – ${v[1]}h` : t.closedDay}</span></div>`).join('');

  $('langLabel').textContent = LANGS.find(l => l[0] === lang)[1];
  $('langList').innerHTML = LANGS.map(([k, label]) => `<button role="option" data-l="${k}" class="${k === lang ? 'on' : ''}">${label}</button>`).join('');
  bindTrack();
}

function setLang(l) {
  lang = l;
  try { localStorage.setItem('kome-lang', l); } catch (e) {}
  closeLang();
  render();
}

const langBtn = $('langBtn'), langList = $('langList');
function closeLang() { langList.hidden = true; langBtn.setAttribute('aria-expanded', 'false'); }
langBtn.addEventListener('click', () => {
  langList.hidden = !langList.hidden;
  langBtn.setAttribute('aria-expanded', String(!langList.hidden));
});
langList.addEventListener('click', e => { const b = e.target.closest('button'); if (b) setLang(b.dataset.l); });
document.addEventListener('pointerdown', e => { if (!$('lang').contains(e.target)) closeLang(); });
document.addEventListener('keydown', e => { if (e.key === 'Escape') closeLang(); });

// Piste des rayons : flèches, drag souris, barre de progression
const track = $('track');
let drag = null;
function updateProgress() {
  const m = track.scrollWidth - track.clientWidth;
  $('prog').style.width = Math.max(8, (m > 0 ? track.scrollLeft / m : 0) * 100) + '%';
}
function scrollByFig(dir) {
  const f = track.querySelector('figure');
  track.scrollBy({ left: dir * ((f && f.offsetWidth) || 600), behavior: 'smooth' });
}
function bindTrack() { updateProgress(); }
$('prev').addEventListener('click', () => scrollByFig(-1));
$('next').addEventListener('click', () => scrollByFig(1));
track.addEventListener('scroll', updateProgress);
track.addEventListener('pointerdown', e => {
  if (e.pointerType !== 'mouse') return;
  drag = { x: e.clientX, s: track.scrollLeft };
  track.style.cursor = 'grabbing';
  track.style.scrollSnapType = 'none';
});
track.addEventListener('pointermove', e => { if (drag) track.scrollLeft = drag.s - (e.clientX - drag.x); });
function endDrag() {
  if (!drag) return;
  drag = null;
  track.style.cursor = 'grab';
  track.style.scrollSnapType = 'x proximity';
}
track.addEventListener('pointerup', endDrag);
track.addEventListener('pointerleave', endDrag);
window.addEventListener('resize', updateProgress);

render();
